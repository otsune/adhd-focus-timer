export function t(key, vars = {}, language = 'ja') {
  const lang = TRANSLATIONS[language] ? language : 'ja';
  const template = TRANSLATIONS[lang][key] ?? TRANSLATIONS.ja[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}